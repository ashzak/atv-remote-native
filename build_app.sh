#!/bin/bash
# Builds the Swift package in release mode and assembles it into a standard
# macOS .app bundle (no Xcode project needed), ad-hoc signs it, and launches
# it. Mirrors what `npm run build` + `electron-builder` did for the old
# Electron app, minus notarization (ad-hoc signing only, for local use).
set -euo pipefail
cd "$(dirname "$0")"

APP_NAME="ATV Remote"
BIN_NAME="ATVRemote"
BUNDLE_ID="com.ashbuilt.atvremote.native"
APP_DIR="dist/${APP_NAME}.app"

echo "==> swift build -c release"
swift build -c release

BIN_PATH=".build/release/${BIN_NAME}"
if [[ ! -x "$BIN_PATH" ]]; then
    echo "Built binary not found at $BIN_PATH" >&2
    exit 1
fi

echo "==> assembling ${APP_DIR}"
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"

cp "$BIN_PATH" "$APP_DIR/Contents/MacOS/$BIN_NAME"
cp Sources/ATVRemote/Resources/*.py Sources/ATVRemote/Resources/*.txt Sources/ATVRemote/Resources/*.sh Sources/ATVRemote/Resources/*.png "$APP_DIR/Contents/Resources/"
chmod +x "$APP_DIR/Contents/Resources/start_server.sh"

# SwiftPM's "Bundle.module" resource bundle (generated by the build) must sit
# in Contents/Resources for Bundle.main.resourceURL lookups to find it.
RES_BUNDLE=".build/release/ATVRemote_ATVRemote.bundle"
if [[ -d "$RES_BUNDLE" ]]; then
    cp -R "$RES_BUNDLE" "$APP_DIR/Contents/Resources/"
fi

cat > "$APP_DIR/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key>
    <string>${BIN_NAME}</string>
    <key>CFBundleIdentifier</key>
    <string>${BUNDLE_ID}</string>
    <key>CFBundleName</key>
    <string>${APP_NAME}</string>
    <key>CFBundleDisplayName</key>
    <string>${APP_NAME}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>1.1.1</string>
    <key>CFBundleVersion</key>
    <string>1.1.1</string>
    <key>LSUIElement</key>
    <true/>
    <key>LSMinimumSystemVersion</key>
    <string>13.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSHumanReadableCopyright</key>
    <string>Copyright 2026</string>
</dict>
</plist>
PLIST

echo "==> codesign (ad-hoc)"
codesign --force --deep -s - "$APP_DIR"
codesign --verify --verbose "$APP_DIR"

echo "==> done: $APP_DIR"

if [[ "${1:-}" == "--run" ]]; then
    echo "==> launching"
    open "$APP_DIR"
fi
